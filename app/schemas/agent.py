from datetime import date, datetime
from typing import Optional
from pydantic import BaseModel, EmailStr, field_validator
from app.models.agent import StipendType, AgentGender


def _validate_phone(v):
    if v is None:
        return v
    if not v.isdigit():
        raise ValueError("Phone must contain digits only")
    if len(v) != 10:
        raise ValueError("Phone must be exactly 10 digits")
    return v


def _validate_pin(v):
    if v is None:
        return v
    if not v.isdigit():
        raise ValueError("PIN code must contain digits only")
    if len(v) != 6:
        raise ValueError("PIN code must be exactly 6 digits")
    return v


# ------------------------------------------------------------------
# Step 1 - Create (minimal)
# ------------------------------------------------------------------

class AgentCreateRequest(BaseModel):
    first_name: str
    last_name: str
    phone: str
    email: EmailStr
    stipend_type: StipendType = StipendType.WITHOUT_STIPEND
    # password is auto-generated by backend and emailed to the agent

    @field_validator("phone")
    @classmethod
    def val_phone(cls, v): return _validate_phone(v)


class AgentCreateResponse(BaseModel):
    detail: str
    user_id: int
    agent_id: str


# ------------------------------------------------------------------
# Step 2 - Profile Update (PATCH, all optional)
# ------------------------------------------------------------------

class AgentProfileUpdate(BaseModel):
    # Step-1 editable fields
    first_name: Optional[str] = None
    last_name: Optional[str] = None
    phone: Optional[str] = None
    email: Optional[EmailStr] = None
    stipend_type: Optional[StipendType] = None

    # Step-2 profile fields
    gender: Optional[AgentGender] = None
    dob: Optional[date] = None
    qualification: Optional[str] = None
    university: Optional[str] = None
    designation: Optional[str] = None
    experience: Optional[str] = None

    # Address / Location
    pin_code: Optional[str] = None
    division: Optional[str] = None
    district: Optional[str] = None
    state: Optional[str] = None
    landmark: Optional[str] = None

    @field_validator("phone")
    @classmethod
    def val_phone(cls, v): return _validate_phone(v)

    @field_validator("pin_code")
    @classmethod
    def val_pin(cls, v): return _validate_pin(v)


